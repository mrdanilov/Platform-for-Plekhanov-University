"""Нормализованные ключи имён — основа, на которой ищутся справочники.

Проблема, которую решает модуль. SQLite и PostgreSQL сравнивают строки
посимвольно: ``ЭК-01`` и ``эк-01`` для них разные значения. Если искать
преподавателя или группу точным ``filter(name=...)``, то каждый «немного
другой» вариант написания в Excel создаёт новый объект. За semester таких
импортов набирается dozens, и расписание распадается: в меню две одинаковые
группы, один предмет показан двумя цветами, а фильтр по преподавателю
отдаёт только часть его занятий.

Поэтому ключ сравнения считается отдельно от отображаемого имени:

* регистр не важен — ``Финансы`` и ``финансы`` это один предмет;
* ``ё`` и ``е`` не различаются — иначе «Фёдоров» и «Федоров» дают двух
  разных преподавателей с половиной расписания у каждого;
* лишние пробелы и неразрывные пробелы схлопываются.

За учебный год таких «немного других» написаний набирается много, поэтому
чинить задним числом дороже, чем не дать дублям появиться.

Ключ хранится в базе отдельным полем (``norm_name`` и т. п.), потому что
ни SQLite, ни переносимый на PostgreSQL вариант ``UniqueConstraint`` не
умеют выражение ``replace('ё', 'е')`` внутри индекса. Денормализация — осознанная
плата: пишется ключ один раз при ``save()``, а искать по нему можно обычным
``filter()`` вместо ``LIKE`` с приведением регистра.
"""

import re

# Пробелы (включая неразрывные) схлопываются в один, края обрезаются.
_WHITESPACE = re.compile(r'\s+')


def norm_text(value):
    """Чистит значение перед сохранением: один пробел, без краёв."""
    if value is None:
        return ''
    return _WHITESPACE.sub(' ', str(value).replace('\xa0', ' ')).strip()


def norm_key(value):
    """Ключ сравнения имён: регистр и «ё» не важны.

    Именно по нему ищется существующий объект, а не по точному значению.
    """
    return norm_text(value).lower().replace('ё', 'е')


def norm_keys(*values):
    """Несколько ключей подряд — для составных ключей вида «корпус + аудитория»."""
    return tuple(norm_key(value) for value in values)
