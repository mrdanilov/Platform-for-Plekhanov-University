"""Собрать тестовый файл расписания вуза.

Файл намеренно повторяет форму настоящего: группы стоят колонками, у каждой
своя колонка «ауд», профиль лежит объединённой ячейкой строкой выше кодов, а
в одной ячейке сразу предмет, тип занятия, должность и фамилия.

Опечатки в файле тоже настоящие — из реальных расписаний:

* ``бизнеселекц.)`` — скобка склеена с названием, без пробела тип не виден;
* ``АрхиповаЗ.З.`` — между фамилией и инициалами нет пробела;
* ``9.00-10.20`` в одном ряду и ``9:05-10:25`` в другом — время пары
  берётся тем, что встретилось чаще;
* «Кураторский час» — не занятие, а встреча, в расписание не попадает;
* профиль в скобках рядом с названием предмета: «История экономики
  (на английском языке) (лекц.)» — тип не в первой скобке.

Скрипт запускается вручную, файл уже в репозитории. Он нужен только для
того, чтобы файл можно было пересобрать после правок:

    python -m schedule.tests_support.build_fixture
"""

import pathlib

import openpyxl

OUT = (pathlib.Path(__file__).resolve().parent.parent
       / 'fixtures' / 'example_week.xlsx')

HEADER = {
    'B2': 'РАСПИСАНИЕ ЗАНЯТИЙ',
    'B3': 'на 1 семестр',
    'D4': 'для студентов 1 курса на 2026-2027 уч. год 8 неделя'
          '   с  19 октября по 23 октября',
    'D5': 'Дата', 'E5': 'Дни недели', 'F5': 'Пара', 'G5': 'Время',
    'H6': '6301 (23 ст.)', 'I6': 'ауд',
    'J6': '6303 (14 ст.)', 'K6': 'ауд',
}

# (день, пара, время, группа 6301, аудитория, группа 6303, аудитория)
ROWS = [
    (19, 1, '9.00-10.20',
     'Микроэкономика (лекц.) доц. Соколова С.', '3/308',
     'Физическая культура (практ.зан.) PhD Рощина И.Ю.', 'спорт зал'),
    (19, 2, '9.00-10.20',
     'История экономических учений (на английском языке) (лекц.) '
     'проф. Крылова Г.Ш.', '1/402',
     'Информационные технологии (лабр.) ст. преп. АрхиповаЗ.З.', '2/105'),
    (20, 1, '9.05-10.25',
     'Планирование и прогнозирование в экономике (практ.зан.) '
     'доц. Ершова М.Э.', '2/105',
     'Кураторский час Крылова Г.Ш.', ''),
    (21, 3, '12.30-13.50',
     # Настоящая склейка из файла вуза: «(лпракт.зан)» вместо «(лекц.)»
     # с уехавшей первой буквой. Тип виден, но открывающая скобка не на
     # месте — без разбора по всем скобкам он остался бы не найден.
     'Гражданское право  (лпракт.зан)\nдоц. Афанасьева Е.Г.', '3/307',
     'Экология и природопользование (лекц.) доц. Романова Н.Э.', '1/201'),
    (22, 2, '10.30-11.50',
     'Логистика (практ.зан.) ст. преп. Аксенов У.Т.', 'спорт зал',
     'Маркетинг (лекц.) доц. Юдина Д.А.', '2/303'),
    (23, 1, '9.00-10.20',
     # Позиция продублирована — так в настоящем файле вуза:
     # «ст. ст. преп.». Одним проходом «ст.» уезжало в название предмета.
     'Бизнес-планирование и прогнозирование деятельности предприятий'
     ' ресторанного бизнеса (лекц.) \nст. ст. преп. Гаврилова А.Н. ',
     '1/304',
     'Налоги и налогообложение (практ.зан..) доц. Ильина С.А.', '3/307'),
]


def build():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = '1 курс '

    for cell, value in HEADER.items():
        ws[cell] = value

    # Профиль объединён на две колонки (код группы и «ауд») и лежит строкой
    # выше кодов. Если это не воспроизвести, профиль в базу не попадёт.
    ws.merge_cells('H5:I5')
    ws['H5'] = 'профиль Экономика и управление человеческим капиталом (ЭиУЧК)'
    ws.merge_cells('J5:K5')
    ws['J5'] = 'профиль Международная торговля'

    weekdays = {19: 'ПОНЕДЕЛЬНИК', 20: 'ВТОРНИК', 21: 'СРЕДА',
                22: 'ЧЕТВЕРГ', 23: 'ПЯТНИЦА'}
    for offset, (day, pair, time, cell_h, room_h, cell_j, room_j) in enumerate(ROWS):
        row = 7 + offset
        ws.cell(row, 4, f'{day}.10.2026 г.')
        ws.cell(row, 5, weekdays[day])
        ws.cell(row, 6, pair)
        ws.cell(row, 7, time)
        ws.cell(row, 8, cell_h)
        ws.cell(row, 9, room_h)
        ws.cell(row, 10, cell_j)
        ws.cell(row, 11, room_j)

    OUT.parent.mkdir(exist_ok=True)
    wb.save(OUT)
    return OUT


if __name__ == '__main__':
    print('записан', build())
